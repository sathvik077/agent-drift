async def verify_audit(request: Request) -> JSONResponse:
    """Recompute the audit HMAC chain, reporting honestly when there is no chain.

    ``configured`` reflects **this store's** key, not the environment, and ``verified`` is
    only ever true after a chain was actually recomputed and matched. Deriving one from
    the environment and the other from a keyless store produced an endpoint that claimed
    verification it had not performed.
    """
    store = get_store(request)
    configured = store.audit_chain_configured
    ok, problem = store.verify_chain()
    env_key_present = os.environ.get("AD_AUDIT_HMAC_KEY") is not None

    if ok is None:
        status = "not_configured"
        note = (
            "No signing key is configured for this store, so there is no chain to verify. "
            "This is reported as 'not configured', never as 'verified'."
        )
        if env_key_present:
            note += (
                " AD_AUDIT_HMAC_KEY is set in the environment but this process did not "
                "load it; restart the control plane so that events are signed."
            )
    elif ok:
        status = "verified"
        note = (
            "An integrity chain is tamper-evidence under a separately held key. A host "
            "compromise that can read the key can also forge the chain, and the chain "
            "covers events and contracts only. See docs/THREAT_MODEL.md section 5.5."
        )
    else:
        status = "broken"
        note = "The recorded chain does not match its contents. Treat this log as untrusted."

    return JSONResponse(
        {
            "configured": configured,
            "verified": ok is True,
            "status": status,
            "events": store.latest_seq(),
            "problem": problem,
            "note": note,
        }
    )


