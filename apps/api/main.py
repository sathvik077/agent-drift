async def get_replay(request: Request) -> JSONResponse:
    """Replay comparison with explicit provenance labels on every row.

    ``observed`` rows are real recorded gateway decisions, including whether the upstream
    tool actually executed. ``simulated`` rows are a counterfactual *computed from the
    same recorded attempt*: what an unguarded passthrough would have attempted. A
    simulated row is never evidence that an incident was prevented in the wild, and the
    payload repeats that where a reader cannot miss it.
    """
    store = get_store(request)
    run_id = request.path_params["run_id"]
    run = store.get_run(run_id)
    if run is None:
        return _error(404, "no such run", code="AD-API-NORUN")

    guarded: list[dict[str, Any]] = []
    simulated: list[dict[str, Any]] = []
    for step in run["steps"]:
        attempt = step["attempt"]
        decision = step["decision"] or {}
        # An attempt row is written *before* evaluation, so its normalized target and
        # destination are not yet known; the decision row carries them. Preferring the
        # decision here is what makes the replay table show what a call actually targeted
        # instead of a dash.
        resource = decision.get("target_resource") or attempt.get("target_resource")
        destination = decision.get("destination") or attempt.get("destination")
        operation = decision.get("operation") or attempt.get("operation")
        guarded.append(
            {
                "source": "observed",
                "provenance": "real recorded gateway decision",
                "attempt_id": attempt.get("attempt_id"),
                "tool": decision.get("tool_name") or attempt.get("tool_name"),
                "operation": operation,
                "resource": resource,
                "destination": destination,
                "args": attempt.get("args"),
                "status": decision.get("status"),
                "reason_codes": decision.get("reason_codes", []),
                "rule_ids": decision.get("rule_ids", []),
                "upstream_executed": step["upstream_executed"],
                "elapsed_ms": decision.get("elapsed_ms"),
                "at": step["at"],
            }
        )
        simulated.append(
            {
                "source": "simulated",
                "provenance": (
                    "hypothetical counterfactual computed from the recorded attempt; "
                    "no tool was run and no incident was prevented in the wild"
                ),
                "attempt_id": attempt.get("attempt_id"),
                "tool": decision.get("tool_name") or attempt.get("tool_name"),
                "operation": operation,
                "resource": resource,
                "destination": destination,
                "status": "would_execute",
                "would_have_executed": True,
                "note": (
                    "Without a gateway the host forwards every proposed call, so an "
                    "unguarded baseline executes this attempt regardless of the contract."
                ),
                "at": step["at"],
            }
        )

    blocked = sum(1 for row in guarded if row["status"] == "deny")
    executed = sum(1 for row in guarded if row["upstream_executed"] == "yes")
    unknown = sum(1 for row in guarded if row["upstream_executed"] == "unknown")
    return JSONResponse(
        {
            "run_id": run_id,
            "task_id": run["task_id"],
            "labels": {
                "observed": "Guarded: real decisions recorded by the gateway",
                "simulated": "Unguarded baseline: simulated counterfactual, not observed",
            },
            "metric_definitions": {
                "attempts": "Number of tool calls the agent attempted through the gateway.",
                "blocked": "Attempts the gateway denied before the upstream tool ran.",
                "executed": "Attempts the gateway forwarded and the upstream tool confirmed it ran.",
                "would_execute_unguarded": (
                    "Attempts an unguarded passthrough would have forwarded. This is a "
                    "simulation over recorded attempts, not an observation."
                ),
                "execution_unknown": (
                    "Attempts the gateway forwarded whose outcome it could not confirm -- "
                    "a timeout or cancellation. The tool may or may not have run, and the "
                    "receipt says so rather than guessing."
                ),
            },
            "summary": {
                "attempts": len(guarded),
                "blocked": blocked,
                "executed": executed,
                "execution_unknown": unknown,
                "would_execute_unguarded": len(simulated),
            },
            "guarded": guarded,
            "unguarded_simulated": simulated,
        }
    )


