async def create_task(request: Request) -> JSONResponse:
    """Register a trusted intent contract."""
    try:
        body = CreateTaskRequest.model_validate(await request.json())
    except ValidationError as exc:
        return _error(422, "payload failed validation", exc.json(), code="AD-API-INVALID")
    except (ValueError, json.JSONDecodeError) as exc:
        return _error(422, "request body was not valid JSON", str(exc), code="AD-API-BADJSON")

    store = get_store(request)
    existing = store.get_contract(body.task_id)
    revision = (existing.policy_revision + 1) if existing else 1

    import datetime as _dt

    contract = IntentContract(
        task_id=body.task_id,
        user_goal=body.user_goal,
        principal=body.principal,
        approved_by=body.approved_by,
        source=body.source,
        allowed_tools=body.allowed_tools,
        allowed_servers=body.allowed_servers,
        allowed_operations=body.allowed_operations,
        resource_scopes=body.resource_scopes,
        allowed_destinations=body.allowed_destinations,
        denied_actions=body.denied_actions,
        max_writes=body.max_writes,
        max_calls=body.max_calls,
        approval_rules=body.approval_rules,
        manifest_drift_policy=body.manifest_drift_policy,
        policy_revision=revision,
        version=revision,
        expires_at=(utcnow() + _dt.timedelta(seconds=body.expires_in_s)) if body.expires_in_s else None,
    )
    try:
        store.put_contract(contract)
    except StoreUnavailable as exc:
        return _error(503, "decision store unavailable", str(exc), code="AD-API-STORE")

    return JSONResponse(
        {
            "task_id": contract.task_id,
            "contract_hash": contract.contract_hash,
            "policy_revision": contract.policy_revision,
            "semantic": contract.semantic_fields(),
            "note": (
                "Registering a new revision invalidates every approval grant issued "
                "against the previous revision."
            ),
        },
        status_code=201,
    )


