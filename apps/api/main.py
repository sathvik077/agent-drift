async def stream_events(request: Request) -> EventSourceResponse:
    """Server-sent event stream of new audit events.

    Polls the store at a short interval. The target is a local end-to-end latency under
    two seconds, which ``tests/e2e/test_dashboard.py::TestLiveUpdates`` and
    ``tests/integration/test_sse_live.py`` measure; this is a *local* target and the README does not dress it up as internet-scale realtime.
    """
    store = get_store(request)
    cursor = _int_param(request, "since", store.latest_seq(), low=0, high=2**62)

    async def generator() -> AsyncIterator[dict[str, Any]]:
        nonlocal cursor
        yield {
            "event": "hello",
            "data": json.dumps(
                {"latest_seq": store.latest_seq(), "since": cursor, "schema_version": SCHEMA_VERSION}
            ),
        }
        idle_ticks = 0
        while True:
            if await request.is_disconnected():
                break
            try:
                events = store.events_since(cursor, limit=100)
            except StoreUnavailable:
                yield {"event": "error", "data": json.dumps({"error": "store unavailable"})}
                await asyncio.sleep(1.0)
                continue
            if events:
                idle_ticks = 0
                for event in events:
                    cursor = max(cursor, int(event["seq"]))
                    yield {"event": "decision", "id": str(event["seq"]), "data": json.dumps(event)}
            else:
                idle_ticks += 1
                if idle_ticks % 20 == 0:  # ~5 s heartbeat so proxies keep the stream open
                    yield {"event": "heartbeat", "data": json.dumps({"latest_seq": cursor})}
            await asyncio.sleep(0.25)

    return EventSourceResponse(generator())


async def list_decisions(request: Request) -> JSONResponse:
    """List recorded decisions, newest first."""
    store = get_store(request)
    task_id = request.query_params.get("task_id")
    status = request.query_params.get("status")
    limit = _int_param(request, "limit", 100, low=1, high=500)

    query = "SELECT payload, created_at, run_id, upstream_executed FROM decisions WHERE 1=1"
    params: list[Any] = []
    if task_id:
        query += " AND task_id = ?"
        params.append(task_id)
    if status:
        query += " AND status = ?"
        params.append(status)
    query += " ORDER BY created_at DESC, rowid DESC LIMIT ?"
    params.append(limit)

    rows = store.conn.execute(query, params).fetchall()
    decisions = []
    for row in rows:
        payload = json.loads(row["payload"])
        payload["run_id"] = row["run_id"]
        payload["upstream_executed"] = bool(row["upstream_executed"])
        decisions.append(payload)
    return JSONResponse({"decisions": decisions, "counts": store.counts()})


