#: Mutating methods require the admin bearer token.
_MUTATING_METHODS = frozenset({"POST", "PUT", "PATCH", "DELETE"})


def _admin_token() -> str | None:
    """The configured admin token, or ``None`` when auth is explicitly disabled."""
    token = os.environ.get("AD_ADMIN_TOKEN", "").strip()
    return token or None


def _auth_disabled() -> bool:
    """True only when the operator opted out explicitly.

    Opting out is allowed for automated tests, but it is an explicit action with an
    explicit name. A missing token does **not** silently disable auth: it fails closed,
    because "the token file was not created" must not mean "anyone may write policy".
    """
    return os.environ.get("AD_DISABLE_AUTH", "").strip() == "1"


def _error(status: int, message: str, detail: str | None = None, code: str | None = None) -> JSONResponse:
    """Build a structured error response."""
    body = ErrorResponse(error=message, detail=detail, code=code)
    return JSONResponse(body.model_dump(mode="json"), status_code=status)


