"""Agent Drift control plane: Starlette application on 127.0.0.1.

Security posture, in order of actual strength:

1. **Bearer token on every mutating request.** The token lives in `.env` as
   ``AD_ADMIN_TOKEN``, is generated by ``make setup``, and is never committed. Comparison
   uses :func:`hmac.compare_digest`. Without it, a browser page or a local process could
   register a permissive contract or approve a pending action -- which is the whole
   authority of the system.
2. **Loopback binding and a CORS allowlist.** Defence in depth. Neither is
   authentication, and the code says so rather than implying otherwise.
3. **Strict request validation.** Every mutating body is parsed by a Pydantic model with
   ``extra="forbid"``.

What is deliberately *not* claimed: this is a single-user development control plane.
Multi-user auth, CSRF tokens for cookie flows, TLS and rate limiting are documented
extensions in ``docs/THREAT_MODEL.md``, not features.
"""

