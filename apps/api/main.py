def _allowed_origins() -> list[str]:
    """CORS allowlist: the dev dashboard origins only."""
    configured = os.environ.get("AD_CORS_ORIGINS")
    if configured:
        return [origin.strip() for origin in configured.split(",") if origin.strip()]
    web_port = os.environ.get("AD_WEB_PORT", "5173")
    api_port = os.environ.get("AD_API_PORT", "8001")
    return [
        f"http://127.0.0.1:{web_port}",
        f"http://localhost:{web_port}",
        f"http://127.0.0.1:{api_port}",
        f"http://localhost:{api_port}",
    ]


def create_app(*, store: Store | None = None) -> Starlette:
    """Build the Starlette application."""
    from starlette.middleware.base import BaseHTTPMiddleware

    routes: list[Any] = list(ROUTES)
    # The built bundle is served under /assets, which is what dist/index.html references.
    # The directory is created if absent so the mount can always be registered: a request
    # for a missing file then 404s, which is a clearer failure than the application
    # refusing to start because the frontend has not been built yet.
    DASHBOARD_DIST.mkdir(parents=True, exist_ok=True)
    routes.append(Mount("/assets", app=StaticFiles(directory=str(DASHBOARD_DIST)), name="assets"))

    app = Starlette(
        debug=False,
        routes=routes,
        middleware=[
            Middleware(
                CORSMiddleware,
                allow_origins=_allowed_origins(),
                allow_methods=["GET", "POST", "OPTIONS"],
                allow_headers=["authorization", "content-type"],
                allow_credentials=False,
            ),
            Middleware(BaseHTTPMiddleware, dispatch=auth_middleware),
        ],
    )

    # The store must be given the signing key here. Reading the key from the environment
    # for reporting while building a keyless store produced an endpoint that claimed
    # verification it had not performed, and made the CLI raise a false tamper alarm on a
    # clean database whose control-plane events were unsigned.
    resolved_store = store or open_default_store()
    app.state.store = resolved_store
    sandbox = os.environ.get("AD_SANDBOX_ROOT")
    app.state.engine = PolicyEngine(resolved_store, sandbox_root=Path(sandbox) if sandbox else None)
    app.state.openapi = build_openapi(_model_schemas())
    return app


app = create_app()
