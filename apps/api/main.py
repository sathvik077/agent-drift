async def evaluate_attempt(request: Request) -> JSONResponse:
    """Evaluate a proposed tool call. Advisory only; see the response ``enforcement`` field."""
    try:
        body = EvaluateAttemptRequest.model_validate(await request.json())
    except ValidationError as exc:
        return _error(422, "payload failed validation", exc.json(), code="AD-API-INVALID")
    except (ValueError, json.JSONDecodeError) as exc:
        return _error(422, "request body was not valid JSON", str(exc), code="AD-API-BADJSON")

    store = get_store(request)
    if store.get_contract(body.task_id) is None:
        return _error(
            404,
            "no contract for task",
            f"register a contract for {body.task_id!r} before evaluating attempts",
            code="AD-API-NOTASK",
        )

    attempt = ToolAttempt(
        task_id=body.task_id,
        tool_server=body.tool_server,
        tool_name=body.tool_name,
        args=body.args,
        **({"run_id": body.run_id} if body.run_id else {}),
    )
    store.record_attempt(attempt)
    decision = get_engine(request).evaluate(
        attempt, bound_task_id=body.task_id, observed_manifest=None, reserve=False
    )
    decision.evidence = {
        **decision.evidence,
        "enforcement": "advisory (control-plane evaluation, not interception)",
    }
    store.record_decision(decision, run_id=attempt.run_id)

    payload = DecisionResponse(
        attempt_id=decision.attempt_id,
        status=str(decision.status),
        reason_codes=decision.reason_codes,
        rule_ids=decision.rule_ids,
        explanations=[explain(code) for code in decision.reason_codes],
        risk=str(decision.risk),
        policy_revision=decision.policy_revision,
        contract_hash=decision.contract_hash,
        resource=attempt.target_resource,
        destination=attempt.destination,
        elapsed_ms=decision.elapsed_ms,
    )
    return JSONResponse(payload.model_dump(mode="json"))


def _int_param(request: Request, name: str, default: int, *, low: int, high: int) -> int:
    """Parse a bounded integer query parameter.

    Returns the default for anything unparseable and clamps to the range, so a malformed
    `?since=x` is a well-formed request for the first page rather than an unhandled
    exception and a 500.
    """
    raw = request.query_params.get(name)
    if raw is None or raw == "":
        return default
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return default
    return max(low, min(value, high))


