async def auth_middleware(request: Request, call_next: Callable[[Request], Awaitable[Response]]) -> Response:
    """Require a bearer token for mutating requests.

    Implemented as pure ASGI middleware rather than a decorator so that a route added
    later cannot accidentally be unprotected.
    """
    if request.method in _MUTATING_METHODS and not _auth_disabled():
        expected = _admin_token()
        if expected is None:
            return _error(
                503,
                "control plane is not configured for mutations",
                "AD_ADMIN_TOKEN is unset. Run `make setup` to generate one, or set "
                "AD_DISABLE_AUTH=1 explicitly for automated tests.",
                code="AD-API-NOTOKEN",
            )
        header = request.headers.get("authorization", "")
        scheme, _, presented = header.partition(" ")
        if scheme.lower() != "bearer" or not presented or not hmac.compare_digest(presented, expected):
            return _error(
                401,
                "missing or invalid bearer token",
                "Mutating requests require `Authorization: Bearer <AD_ADMIN_TOKEN>`.",
                code="AD-API-UNAUTHORIZED",
            )
    return await call_next(request)


